/**
 * Builds the exam report a learner sends to Claude: everything needed to grade open answers,
 * review SQL/dbt work, calibrate the level against the target job ad, and write a focus plan.
 */
import { DOMAIN_BY_ID, DOMAINS } from '../content/domains';
import type { Item } from '../content/types';
import type { Attempt, ExamSession } from '../store/progress';
import { practiceMastery, scoreExam, type ExamResult } from './scoring';
import type { ProjectFiles } from './dbt/types';
import { applyOverrides } from './grading';
import { TIDEPOOL_PROJECT } from './dbt/tidepoolProject';

const pct = (x: number | null) => (x === null ? '—' : `${Math.round(x * 100)}%`);

function fence(lang: string, body: string) {
  const ticks = body.includes('```') ? '````' : '```';
  return `${ticks}${lang}\n${body.trim()}\n${ticks}`;
}

function answerBlock(item: Item, answer: unknown, files?: ProjectFiles): string {
  switch (item.kind) {
    case 'mcq': {
      const sel = Array.isArray(answer) ? (answer as number[]) : [];
      const lines = item.options.map((o, i) => `${sel.includes(i) ? '[x]' : '[ ]'} ${String.fromCharCode(65 + i)}. ${o}${item.correct.includes(i) ? '  ← correct' : ''}`);
      return lines.join('\n');
    }
    case 'order': {
      const order = Array.isArray(answer) ? (answer as string[]) : [];
      return `Candidate order:\n${order.map((s, i) => `${i + 1}. ${s}`).join('\n') || '(not answered)'}\n\nCorrect order:\n${item.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}`;
    }
    case 'sql':
      return fence('sql', typeof answer === 'string' && answer.trim() ? answer : '-- (no query submitted)');
    case 'numeric':
      return `Candidate answer: ${answer ?? '(none)'}`;
    case 'open':
      return typeof answer === 'string' && answer.trim() ? answer.trim() : '(no answer)';
    case 'dbt': {
      if (!files) return '(no files changed)';
      const base = applyOverrides(TIDEPOOL_PROJECT, item.files);
      const changed = Object.keys(files).filter((p) => files[p] !== base[p]);
      if (!changed.length) return '(no files changed)';
      return changed.map((p) => `File \`${p}\`:\n${fence(p.endsWith('.sql') ? 'sql' : 'yaml', files[p])}`).join('\n\n');
    }
  }
}

export interface ReportInput {
  exam: ExamSession;
  items: Item[];
  practice: { items: Item[]; progress: Record<string, Attempt> };
}

export function buildExamReport({ exam, items, practice }: ReportInput): { markdown: string; json: unknown; result: ExamResult } {
  const result = scoreExam(exam, items);
  const mastery = practiceMastery(practice.items, practice.progress);
  const date = new Date(exam.finishedAt ?? Date.now());
  const c = exam.candidate;

  const md: string[] = [];
  md.push(`# AE Licence — exam report`);
  md.push('');
  md.push(`Generated by the AE Licence app (practice + exam for analytics engineering; synthetic company "Tidepool Coffee Co.", SQL run on DuckDB, a dbt-like engine in the browser).`);
  md.push('');
  md.push(`- **Candidate:** ${c.name || '(not given)'}`);
  md.push(`- **Background:** ${c.background || '(not given)'}`);
  md.push(`- **Years of relevant experience:** ${c.yearsExperience || '(not given)'}`);
  md.push(`- **Goals:** ${c.goals || '(not given)'}`);
  md.push(`- **Taken:** ${date.toISOString().slice(0, 16).replace('T', ' ')} UTC · ${result.minutes} min of a ${exam.timeLimitMin}-min limit`);
  md.push('');
  md.push(`## Auto-graded summary`);
  md.push('');
  md.push(`- **Auto-graded score:** ${pct(result.overall)} (${result.answered}/${result.autoTotal} auto-graded tasks answered, weighted by difficulty 1–3)`);
  md.push(`- **Senior-difficulty tasks:** ${pct(result.hardPct)}`);
  md.push(`- **Provisional level (before your review of open answers):** ${result.level.code} ${result.level.plate}: ${result.level.role}. ${result.levelReason}`);
  md.push(`- **Open answers awaiting your grading:** ${result.openPending}`);
  md.push(
    `- **Confidence calibration (1–5 self-rating):** avg ${result.calibration.avgConfCorrect?.toFixed(1) ?? '—'} on correct vs ${result.calibration.avgConfWrong?.toFixed(1) ?? '—'} on incorrect; ${result.calibration.confidentWrong} confident-but-wrong; ${result.calibration.unsureRight} unsure-but-right`,
  );
  md.push('');
  md.push(`| Discipline | Job-ad requirement | Exam (auto) | Practice mastery |`);
  md.push(`|---|---|---|---|`);
  for (const d of DOMAINS) {
    const e = result.byDomain.find((x) => x.domain === d.id)!;
    const p = mastery.find((x) => x.domain === d.id)!;
    md.push(`| ${d.name} | ${d.jobAd} | ${pct(e.pct)} | ${pct(p.pct)} (${p.answered}/${p.total} tried) |`);
  }
  md.push('');
  md.push(`## Target role (job ad supplied by the candidate)`);
  md.push('');
  md.push(fence('text', c.jobAd || '(none)'));
  md.push('');
  md.push(`## Task-by-task`);
  md.push('');
  items.forEach((item, n) => {
    const a = exam.answers[item.id];
    const status = !a ? 'NOT ANSWERED' : item.kind === 'open' ? 'NEEDS CLAUDE GRADING' : a.status === 'correct' ? 'CORRECT' : a.status === 'partial' ? `PARTIAL (${Math.round(a.score * 100)}%)` : 'INCORRECT';
    md.push(`### ${n + 1}. ${item.title} — ${status}`);
    md.push('');
    md.push(`\`${item.id}\` · ${DOMAIN_BY_ID[item.domain].name} · difficulty ${item.difficulty}/3 · ${item.kind}${a ? ` · ${Math.round(a.seconds / 6) / 10} min · confidence ${a.confidence ?? '—'}/5${a.flagged ? ' · flagged' : ''}` : ''}`);
    md.push('');
    md.push(`**Task**`);
    md.push('');
    md.push(item.prompt.trim());
    md.push('');
    md.push(`**Candidate's answer**`);
    md.push('');
    md.push(answerBlock(item, a?.answer, exam.files[item.id]));
    if (a?.feedback && item.kind !== 'open') {
      md.push('');
      md.push(`**Auto-grader:** ${a.feedback}`);
    }
    if (item.explanation) {
      md.push('');
      md.push(`**Reference explanation:** ${item.explanation.trim()}`);
    }
    if (item.kind === 'sql' || item.kind === 'numeric') {
      md.push('');
      md.push(`**Reference solution**`);
      md.push('');
      md.push(fence('sql', item.solution));
    }
    if (item.kind === 'open') {
      md.push('');
      md.push(`**Rubric (what a strong answer covers)**`);
      md.push('');
      md.push(item.rubric.map((r) => `- ${r}`).join('\n'));
    }
    md.push('');
  });
  md.push(`## Instructions for Claude`);
  md.push('');
  md.push(`You are an experienced analytics engineering hiring manager and mentor. Using this report:`);
  md.push('');
  md.push(`1. **Grade each open answer** 0–10 against its rubric, with one or two sentences of specific feedback (quote the candidate where useful).`);
  md.push(`2. **Review the SQL and dbt work** for correctness *and* craft: readability, grain awareness, null handling, performance, naming, testing habits. Note anything the auto-grader could not see.`);
  md.push(`3. **Calibrate the level** (L1 Learner permit · L2 Provisional/Junior · L3 Full licence/Mid · L4 Advanced/Senior · L5 Instructor/Staff), combining the auto-graded score, your grades of the open answers, the confidence calibration, and the candidate's background. Explain the call in 3–5 sentences, and say how confident you are.`);
  md.push(`4. **Assess fit against the target job ad**: for each requirement, rate it as strong / adequate / gap, with evidence from this exam.`);
  md.push(`5. **Write a focused 4-week plan**: the 3 highest-leverage gaps, concrete exercises (the app's modules, gym drills and workday events are listed by id above), and what "good" looks like at the end of each week.`);
  md.push(`6. Finish with **3 interview questions** this candidate should prepare for, given their weakest areas.`);
  md.push('');
  md.push(`Be direct and specific; this person wants an honest read, not encouragement.`);

  const json = {
    app: 'ae-licence',
    version: 1,
    candidate: c,
    startedAt: new Date(exam.startedAt).toISOString(),
    finishedAt: exam.finishedAt ? new Date(exam.finishedAt).toISOString() : null,
    result: { ...result, level: result.level.code },
    practiceMastery: mastery,
    answers: items.map((i) => ({ id: i.id, kind: i.kind, domain: i.domain, difficulty: i.difficulty, ...exam.answers[i.id], files: exam.files[i.id] ? '(see markdown)' : undefined })),
  };

  return { markdown: md.join('\n'), json, result };
}

/** A shorter report of practice progress only (no exam). */
export function buildPracticeReport(items: Item[], progress: Record<string, Attempt>, profile: { name: string; background: string; jobAd: string }): string {
  const mastery = practiceMastery(items, progress);
  const md: string[] = [];
  md.push('# AE Licence — practice progress');
  md.push('');
  md.push(`- **Name:** ${profile.name || '(not given)'}`);
  md.push(`- **Background:** ${profile.background || '(not given)'}`);
  md.push('');
  md.push('| Discipline | Mastery | Tried |');
  md.push('|---|---|---|');
  for (const m of mastery) md.push(`| ${DOMAIN_BY_ID[m.domain].name} | ${pct(m.pct)} | ${m.answered}/${m.total} |`);
  md.push('');
  const misses = items.filter((i) => progress[i.id] && progress[i.id].status !== 'correct' && i.kind !== 'open');
  if (misses.length) {
    md.push('## Items not yet solved');
    md.push('');
    for (const i of misses) md.push(`- \`${i.id}\` (${DOMAIN_BY_ID[i.domain].short}, d${i.difficulty}): ${i.title} — ${progress[i.id].attempts} attempt(s)`);
    md.push('');
  }
  const opens = items.filter((i) => i.kind === 'open' && typeof progress[i.id]?.answer === 'string');
  if (opens.length) {
    md.push('## Open answers');
    md.push('');
    for (const i of opens) {
      if (i.kind !== 'open') continue;
      md.push(`### ${i.title} (\`${i.id}\`)`);
      md.push('');
      md.push(i.prompt.trim());
      md.push('');
      md.push(`**Answer:** ${String(progress[i.id].answer).trim()}`);
      md.push('');
      md.push(`**Rubric:**\n${i.rubric.map((r) => `- ${r}`).join('\n')}`);
      md.push('');
    }
  }
  md.push('## Instructions for Claude');
  md.push('');
  md.push('Grade the open answers against their rubrics, point out the patterns in what I have not solved yet, and suggest what to practise next for this target role:');
  md.push('');
  md.push(fence('text', profile.jobAd));
  return md.join('\n');
}
